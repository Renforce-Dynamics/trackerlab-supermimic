"""State-free arm action rate limiting for learned stealth postures."""

from __future__ import annotations

import math
from collections.abc import Mapping
from typing import Optional

import torch
from torch import nn

from .stealth_upper_body import _finite_vector, _upper_indices


class UpperBodyRateLimiter(nn.Module):
    """Limit arm target motion in radians, leaving all other actions untouched.

    Selects shoulder, elbow and wrist joints (14 on G1). The caller supplies
    the two previous executed actions; no reference pose or rollout state is
    retained. Entry time is accepted for compatibility and has no effect.

    This uses UpperBodyConstraint's tanh rate step and acceleration clamp,
    with a discrete braking envelope to stop within the action range. Bounds
    hold from a stationary in-range history or one generated by this limiter.
    Infeasible external histories prioritize rate/action limits. These bounds
    describe target motion, not physical PD tracking or geometric clearance.
    """

    def __init__(
        self,
        joint_names,
        action_scale,
        max_joint_rate_rad_s=1.2,
        max_joint_acceleration_rad_s2=3.,
        control_dt=.02,
        action_limit=20.,
    ):
        super().__init__()
        names, indices = _upper_indices(joint_names)
        scale = _finite_vector(action_scale, "action_scale").detach().clone()
        if scale.shape != (len(names),):
            raise ValueError("action_scale must match joint_names")
        if bool((scale <= 0).any()):
            raise ValueError("action_scale entries must be positive")
        for name, value in (
            ("max_joint_rate_rad_s", max_joint_rate_rad_s),
            ("max_joint_acceleration_rad_s2", max_joint_acceleration_rad_s2),
            ("control_dt", control_dt),
            ("action_limit", action_limit),
        ):
            if (isinstance(value, bool) or not isinstance(value, (int, float))
                    or not math.isfinite(value) or value <= 0):
                raise ValueError(f"{name} must be finite and positive")
        self.joint_names = names
        self.num_joints = len(names)
        self.upper_joint_names = tuple(names[index] for index in indices)
        self.max_joint_rate_rad_s = float(max_joint_rate_rad_s)
        self.max_joint_acceleration_rad_s2 = float(max_joint_acceleration_rad_s2)
        self.control_dt = float(control_dt)
        self.action_limit = float(action_limit)
        self.register_buffer("upper_indices", torch.tensor(indices, dtype=torch.long))
        self.register_buffer("action_scale", scale)

    def forward(
        self,
        raw_action: torch.Tensor,
        previous_applied_action: torch.Tensor,
        previous_previous_action: torch.Tensor,
        entry_time: Optional[torch.Tensor] = None,
    ) -> torch.Tensor:
        if not torch.jit.is_tracing():
            if (raw_action.ndim < 1 or raw_action.shape[-1] != self.num_joints
                    or previous_applied_action.shape != raw_action.shape
                    or previous_previous_action.shape != raw_action.shape):
                raise ValueError("All three actions must have matching shapes ending in num_joints")
            for value in (raw_action, previous_applied_action, previous_previous_action):
                if value.device != self.action_scale.device or value.dtype != self.action_scale.dtype:
                    raise ValueError("Actions and limiter buffers must share device and dtype")
        scale = self.action_scale.index_select(0, self.upper_indices)
        raw = raw_action.index_select(-1, self.upper_indices)
        previous = previous_applied_action.index_select(-1, self.upper_indices)
        older = previous_previous_action.index_select(-1, self.upper_indices)
        max_step = self.max_joint_rate_rad_s * self.control_dt
        step = max_step * torch.tanh(((raw - previous) * scale) / max_step)
        previous_step = (previous - older) * scale
        max_change = self.max_joint_acceleration_rad_s2 * self.control_dt**2
        step = previous_step + (step - previous_step).clamp(-max_change, max_change)
        step = step.clamp(-max_step, max_step)
        # Invert the discrete stopping distance s + max(s-a, 0) + ... in each
        # direction; final action clipping alone would abruptly violate acceleration.
        room = torch.stack((self.action_limit + previous, self.action_limit - previous), -1)
        room = room.clamp_min(0) * scale[..., None]
        braking_steps = torch.floor((torch.sqrt(1 + 8 * room / max_change) - 1) / 2)
        braking_limit = room / (braking_steps + 1) + .5 * braking_steps * max_change
        step = step.clamp(min=-braking_limit[..., 0], max=braking_limit[..., 1])
        arm_action = (previous + step / scale).clamp(-self.action_limit, self.action_limit)
        return raw_action.index_copy(-1, self.upper_indices, arm_action)

    def to_dict(self):
        """Independent JSON-compatible constructor metadata for the rate limiter."""
        return {
            "joint_names": list(self.joint_names),
            "action_scale": self.action_scale.detach().cpu().tolist(),
            "max_joint_rate_rad_s": self.max_joint_rate_rad_s,
            "max_joint_acceleration_rad_s2": self.max_joint_acceleration_rad_s2,
            "control_dt": self.control_dt,
            "action_limit": self.action_limit,
        }

    @classmethod
    def from_dict(cls, config):
        if not isinstance(config, Mapping):
            raise ValueError("Rate-limiter config must be a mapping")
        return cls(**dict(config))
